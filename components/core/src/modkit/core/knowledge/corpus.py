"""The corpus: every record, topic, citation and component visible from a set of roots.

A root is one folder holding a ``knowledge/`` folder: a component of a repository (its visibility is the
repository's ``modkit.repo.toml``) or a modder's project (always private). ``discover`` finds the roots of a
repository, the components of other repositories reached through installed ``modkit.*`` packages, and a project
folder; ``load`` reads them. A root's ``knowledge/`` holds ``mechanisms/``, ``trials/`` and ``lessons/`` (one record
per file) and ``topics.md`` (the topics its mechanisms are filed under).
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from modkit.core import components
from modkit.core.knowledge import frontmatter, schema
from modkit.core.knowledge.schema import Citation, Lesson, Mechanism, Topic, Trial, Where

FOOTER_START = components.FOOTER_START
FOOTER_END = components.FOOTER_END
# The first line of every generated page; a file that starts with it may be rewritten or deleted by ``render``.
GENERATED = "<!-- Generated by `python -m modkit.core.knowledge render`. Do not edit by hand. -->"
PROJECT = "project"
MAX_SCAN_BYTES = 2 * 1024 * 1024
SKIP_DIRS = components.SKIP_DIRS


@dataclass(frozen=True)
class Root:
    """A folder holding ``knowledge/``: a component, or a project."""
    name: str
    path: Path
    visibility: str  # public | private
    repo_root: Path
    deps: frozenset[str] = frozenset()
    is_project: bool = False
    description: str = ""

    @property
    def knowledge(self) -> Path:
        return self.path / "knowledge"

    @property
    def src(self) -> Path:
        return self.path / "src" / "modkit" / self.name

    def where(self, path: Path) -> Where:
        return Where(self.name, self.visibility, _posix(self.repo_root), _posix(path))


@dataclass(frozen=True)
class Issue:
    """A problem met while loading: bad front matter, a schema violation, a duplicate ID."""
    repo_root: str
    component: str
    path: str
    text: str


@dataclass
class Corpus:
    roots: dict[str, Root] = field(default_factory=dict)
    mechanisms: dict[str, Mechanism] = field(default_factory=dict)
    trials: dict[str, Trial] = field(default_factory=dict)
    lessons: dict[str, Lesson] = field(default_factory=dict)
    topics: dict[str, Topic] = field(default_factory=dict)
    citations: list[Citation] = field(default_factory=list)
    issues: list[Issue] = field(default_factory=list)

    def record(self, id_: str):
        """The mechanism, trial or lesson with this ID (IDs are global), or None."""
        return self.mechanisms.get(id_) or self.trials.get(id_) or self.lessons.get(id_)

    def graph(self) -> dict[str, set[str]]:
        return {name: set(root.deps) for name, root in self.roots.items()}

    def closure(self, name: str) -> set[str]:
        return components.dependency_closure(name, self.graph())

    def restricted(self, visibility: str) -> "Corpus":
        """The part of the corpus with this visibility only (what a repository of that visibility may show)."""
        def keep(x) -> bool:
            return x.where.visibility == visibility

        return Corpus(
            roots={n: r for n, r in self.roots.items() if r.visibility == visibility},
            mechanisms={k: v for k, v in self.mechanisms.items() if keep(v)},
            trials={k: v for k, v in self.trials.items() if keep(v)},
            lessons={k: v for k, v in self.lessons.items() if keep(v)},
            topics={k: v for k, v in self.topics.items() if keep(v)},
            citations=[c for c in self.citations if keep(c)],
            issues=[i for i in self.issues if self.roots.get(i.component) is None
                    or self.roots[i.component].visibility == visibility])


def _posix(path: Path | str) -> str:
    return str(path).replace("\\", "/")


def strip_footer(text: str) -> str:
    """The text without the generated "referenced by" block."""
    start = text.find(FOOTER_START)
    if start < 0:
        return text
    end = text.find(FOOTER_END, start)
    if end < 0:
        return text[:start]
    return text[:start] + text[end + len(FOOTER_END):]


def _read(path: Path) -> str:
    return path.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")


def is_generated(path: Path) -> bool:
    """Whether the file starts with the generated-page header (so ``render`` owns it)."""
    try:
        with open(path, "rb") as fh:
            head = fh.read(len(GENERATED.encode("utf-8")) + 3)
    except OSError:
        return False
    return head.decode("utf-8-sig", "replace").startswith(GENERATED)


def _description(comp: Path) -> str:
    try:
        data = json.loads((comp / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))
        return str(data.get("description", "")) if isinstance(data, dict) else ""
    except (OSError, ValueError):
        return ""


def _repo_visibility(repo_root: Path) -> str:
    return components.visibility(repo_root) or "public"  # an unmarked repository is held to the stricter rule


def repo_roots(repo_root: Path) -> list[Root]:
    """The components of one repository."""
    repo_root = Path(repo_root)
    vis = _repo_visibility(repo_root)
    return [Root(name, repo_root / "components" / name, vis, repo_root,
                 frozenset(components.declared_dependencies(repo_root / "components" / name)),
                 description=_description(repo_root / "components" / name))
            for name in components.repo_components(repo_root)]


def project_root(path: Path) -> Root:
    """A modder's project folder; its ``knowledge/`` holds their own records. It counts as private."""
    path = Path(path)
    return Root(PROJECT, path, "private", path, is_project=True)


def installed_roots(skip_names=(), skip_paths=()) -> list[Root]:
    """Components of other repositories, found through installed ``modkit.*`` packages."""
    out = []
    skip_paths = {Path(p).resolve() for p in skip_paths}
    for name, comp in sorted(components.installed_components().items()):
        if name in skip_names or comp.resolve() in skip_paths or not (comp / "knowledge").is_dir():
            continue
        repo = comp.parent.parent if comp.parent.name == "components" else comp.parent
        out.append(Root(name, comp, _repo_visibility(repo), repo, frozenset(components.declared_dependencies(comp)),
                        description=_description(comp)))
    return out


def discover(repo_root: Path | None = None, project: Path | None = None) -> list[Root]:
    """The roots visible from a repository (its components, then installed components of other repositories)
    and/or a project folder with a ``knowledge/`` folder. A project folder inside the repository is not one."""
    roots = repo_roots(repo_root) if repo_root is not None else []
    roots += installed_roots({r.name for r in roots}, [r.path for r in roots])
    if project is not None and (Path(project) / "knowledge").is_dir():
        here = Path(project).resolve()
        inside = any(here == r.path.resolve() or r.path.resolve() in here.parents for r in roots)
        if repo_root is not None and (here == Path(repo_root).resolve() or Path(repo_root).resolve() in here.parents):
            inside = True
        if not inside:
            roots.append(project_root(project))
    return roots


def _citations_in(text: str) -> list[str]:
    return list(dict.fromkeys(m.group(1).strip() for m in schema.CITATION_RE.finditer(text)))


def _scan_citations(root: Root, out: list[Citation]) -> None:
    for sub, kind in (("skills", "skill"), ("examples", "example")):
        folder = root.path / sub
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob("*")):
            rel = path.relative_to(folder).parts
            if not path.is_file() or SKIP_DIRS & set(rel) or path.name == ".gitkeep":
                continue
            try:
                if path.stat().st_size > MAX_SCAN_BYTES:
                    continue
                data = path.read_bytes()
                if b"\0" in data:
                    continue
                text = data.decode("utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            for cited in _citations_in(text):
                out.append(Citation(cited, kind, "", root.where(path)))


def _load_records(root: Root, corpus: Corpus, owners: dict[str, str]) -> None:
    def issue(path: Path, text: str) -> None:
        corpus.issues.append(Issue(_posix(root.repo_root), root.name, _posix(path), text))

    def register(id_: str, record, path: Path, store: dict) -> bool:
        if id_ in owners:
            issue(path, f"duplicate ID {id_} (already defined in {owners[id_]})")
            return False
        owners[id_] = _posix(path)
        store[id_] = record
        return True

    for sub, kind, store, build in (("mechanisms", "mechanism", corpus.mechanisms, schema.mechanism_from),
                                    ("trials", "trial", corpus.trials, schema.trial_from),
                                    ("lessons", "lesson", corpus.lessons, schema.lesson_from)):
        folder = root.knowledge / sub
        for path in sorted(folder.glob("*.md")) if folder.is_dir() else []:
            try:
                meta, body = frontmatter.parse(_read(path))
                raw_body = body
                body = strip_footer(body).rstrip("\n")
                record = build(meta, body + "\n" if body else "", root.where(path))
            except frontmatter.FrontMatterError as exc:
                issue(path, f"front matter: {exc}")
                continue
            except schema.SchemaError as exc:
                for problem in exc.problems:
                    issue(path, f"{kind} {path.stem}: {problem}")
                continue
            if record.id != path.stem:
                issue(path, f"{kind} {record.id}: the file name must be {record.id}.md")
                continue
            starts, ends = raw_body.count(FOOTER_START), raw_body.count(FOOTER_END)
            if (starts, ends) not in ((0, 0), (1, 1)) or raw_body.find(FOOTER_START) > raw_body.find(FOOTER_END) >= 0:
                issue(path, f"{kind} {record.id}: unclosed or repeated referenced-by marker (the block must be "
                            "one start line and one end line, written by render)")
            if register(record.id, record, path, store):
                # citations are read from the whole text, footer included: nothing in a footer is trusted
                for cited in _citations_in(raw_body):
                    corpus.citations.append(Citation(cited, "record", record.id, record.where))
    old = root.knowledge / "lessons.md"
    if old.is_file() and not is_generated(old):  # a project's generated lessons page sits at the same path
        issue(old, "lessons.md is the old one-file form: move each `## <id>: <rule>` section to "
                   "lessons/<id>.md (front matter id, title, trials; the prose as the body) and delete it")
    topics_path = root.knowledge / "topics.md"
    if topics_path.is_file():
        topics, problems = schema.parse_topics(_read(topics_path), root.where(topics_path))
        for text in problems:
            issue(topics_path, text)
        for topic in topics:
            if topic.id in corpus.topics:
                issue(topics_path, f"duplicate topic ID {topic.id} (already declared in {corpus.topics[topic.id].where.path})")
            else:
                corpus.topics[topic.id] = topic
    if not root.is_project:
        _scan_citations(root, corpus.citations)


def load(roots) -> Corpus:
    """Read every root. A repeated ID or component name is recorded as an issue; the first one wins."""
    corpus = Corpus()
    owners: dict[str, str] = {}
    for root in roots:
        if root.name in corpus.roots:
            corpus.issues.append(Issue(_posix(root.repo_root), root.name, _posix(root.path),
                                       f"component {root.name} is found twice ({corpus.roots[root.name].path})"))
            continue
        corpus.roots[root.name] = root
        _load_records(root, corpus, owners)
    return corpus


def load_repo(repo_root: Path, project: Path | None = None) -> Corpus:
    """The corpus visible from a repository (plus a project folder, if given)."""
    return load(discover(repo_root, project))


def is_repo(root: Path) -> bool:
    """Whether ``root`` is a repository (it has ``modkit.repo.toml``); otherwise it is read as a project folder."""
    return components.visibility(Path(root)) is not None


def load_folder(root: Path) -> Corpus:
    """The corpus visible from ``root``: a repository, or a modder's project folder with a ``knowledge/`` folder."""
    return load_repo(root) if is_repo(root) else load(discover(None, root))
